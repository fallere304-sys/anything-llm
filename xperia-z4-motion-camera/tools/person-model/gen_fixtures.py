#!/usr/bin/env python3
"""Writes app/src/test/java/com/z4motioncam/BodyModelFixtures.java from `reference.py fixtures <model>` output.

  python3 reference.py fixtures detect.tflite > /tmp/fx.json && python3 gen_fixtures.py /tmp/fx.json > BodyModelFixtures.java
"""
import json
import sys

d = json.load(open(sys.argv[1]))
o = []
o.append("package com.z4motioncam;\n")
o.append("/** GENERATED by tools/person-model/gen_fixtures.py from reference.py (numpy + the real model). Do not edit by hand. */")
o.append("final class BodyModelFixtures {")
o.append("    private BodyModelFixtures() {}\n")
o.append("    static final class Crop {\n        final String key;\n        final double mean;\n        final long sum;\n        final long wsum;\n        final int[] pts;\n")
o.append("        Crop(String key, double mean, long sum, long wsum, int[] pts) {\n            this.key = key;\n            this.mean = mean;\n            this.sum = sum;\n            this.wsum = wsum;\n            this.pts = pts;\n        }\n    }\n")
o.append("    static final Crop[] CROPS = {")
for k, v in d["crops"].items():
    pts = ",".join(str(x) for p in v["pts"] for x in p)
    o.append('        new Crop("%s", %r, %dL, %dL, new int[] {%s}),' % (k, v["mean"], v["sum"], v["wsum"], pts))
o.append("    };\n")
o.append("    /** {mean luma, expected gamma}. */\n    static final double[][] GAMMA = {")
for k, v in d["gamma"].items():
    o.append("        {%s, %s}," % (k, repr(v)))
o.append("    };\n")
o.append("    /** What the real model answered for the \"square\" crop of the synthetic frame (not a scene: numbers for the decoder). */")
o.append("    static final class Answer {\n        final String key;\n        final int count;\n        final float[] boxes;\n        final float[] classes;\n        final float[] scores;\n")
o.append("        Answer(String key, int count, float[] boxes, float[] classes, float[] scores) {\n            this.key = key;\n            this.count = count;\n            this.boxes = boxes;\n            this.classes = classes;\n            this.scores = scores;\n        }\n    }\n")
def fl(a): return ",".join("%sf" % repr(float(x)) for x in a)
o.append("    static final Answer[] ANSWERS = {")
for k, v in d["model"].items():
    o.append('        new Answer("%s", %d, new float[] {%s}, new float[] {%s}, new float[] {%s}),' % (k, v["count"], fl(v["boxes"]), fl(v["classes"]), fl(v["scores"])))
o.append("    };")
o.append("}")
print("\n".join(o))
